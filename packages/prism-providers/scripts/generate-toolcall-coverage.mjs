#!/usr/bin/env node
/**
 * Generates docs/_evidence/toolcall-coverage-2026-09-17.md from compiled
 * static provider catalogs — the data toolcall-conformance.test.ts asserts.
 * Run: node scripts/generate-toolcall-coverage.mjs (from packages/prism-providers).
 */
import { writeFileSync } from "node:fs";

const root = new URL("../../../", import.meta.url).pathname;

async function load(provider, name) {
  const mod = await import(`../dist/${provider}/index.js`);
  return mod[name];
}

const CATALOGS = [
  ["anthropic", "anthropic", "anthropicModels"],
  ["openai", "openai", "openAIModels"],
  ["openai-codex", "openai", "openAICodexModels"],
  ["google", "google", "googleModels"],
  ["kimi-coding", "kimi", "kimiCodingModels"],
  ["kimi-moonshot", "kimi", "moonshotKimiModels"],
  ["zai", "zai", "zaiModels"],
  ["xai", "xai", "xaiModels"],
  ["deepseek", "deepseek", "deepseekModels"],
  ["hyper", "hyper", "hyperModels"],
  ["clinepass", "clinepass", "clinePassModels"],
  ["neuralwatt", "neuralwatt", "neuralWattModels"],
  ["opencode-go", "opencode-go", "openCodeGoModels"],
  ["commandcode", "commandcode", "commandCodeModels"],
];

const STRICT_EVIDENCE = {
  neuralwatt:
    "packages/prism-providers/src/neuralwatt/__tests__/neuralwatt.test.ts (parallel indexed calls, schema-shaped arguments, empty `{}` arguments)",
};
const unknownEvidence = (catalog) =>
  `packages/prism-providers/src/__tests__/toolcall-conformance.test.ts (explicit unstamped-unknown: ${catalog})`;

const rows = [];
for (const [id, dir, exportName] of CATALOGS) {
  const models = await load(dir, exportName);
  for (const model of models) {
    if (model.capabilities?.tools !== true) continue;
    const strictness = model.capabilities.toolCallStrictness;
    rows.push({
      catalog: id,
      model: model.model,
      strictness: strictness ?? "unknown (unstamped)",
      evidence: strictness ? STRICT_EVIDENCE[id] : unknownEvidence(id),
    });
  }
}

const strict = rows.filter((row) => row.strictness === "strict").length;
const unknown = rows.length - strict;
const lines = [
  "# Tool-call reliability evidence matrix (2026-09-17)",
  "",
  "Generated by `scripts/generate-toolcall-coverage.mjs` from compiled static provider catalogs —",
  "the exact declaration policy `packages/prism-providers/src/__tests__/toolcall-conformance.test.ts` asserts.",
  "Regenerate after catalog or fixture changes: `node scripts/generate-toolcall-coverage.mjs`.",
  "",
  "`strict` means Prism's network-free adapter fixture covers parallel-call reconstruction, a schema-shaped argument object, and an empty `{}` argument object. It is not a provider SLA; hosts still validate tool arguments. `lenient` and `legacy` have no current first-party stamps. Dynamic discovery records are omitted because untrusted provider metadata cannot earn a catalog stamp.",
  "",
  "| Provider catalog | Model | toolCallStrictness | Evidence |",
  "| --- | --- | --- | --- |",
  ...rows.map((row) => `| ${row.catalog} | \`${row.model}\` | ${row.strictness} | ${row.evidence} |`),
  "",
  `Coverage: ${rows.length} static catalog models advertising tools across ${CATALOGS.length} first-party catalogs (${strict} strict, ${unknown} explicitly unstamped unknown).`,
  "",
];

writeFileSync(`${root}docs/_evidence/toolcall-coverage-2026-09-17.md`, lines.join("\n"));
console.log(`wrote docs/_evidence/toolcall-coverage-2026-09-17.md (${rows.length} rows)`);
