#!/usr/bin/env node
/**
 * Generates docs/_evidence/thinking-coverage-2026-09-05.md from the compiled
 * provider catalogs — the same data the thinking-conformance walk asserts.
 * Run: node scripts/generate-thinking-coverage.mjs (from packages/prism-providers).
 */
import { writeFileSync } from "node:fs";

const root = new URL("../../../", import.meta.url).pathname;

async function load(provider, name) {
  const mod = await import(`../dist/${provider}/index.js`);
  return mod[name];
}

/** Provenance: levels source (API-derived vs hardcoded) + documentation URL. */
const SOURCES = {
  anthropic: ["hardcoded", "https://docs.anthropic.com/en/docs/build-with-claude/effort"],
  openai: ["hardcoded", "https://developers.openai.com/api/docs/models"],
  "openai-codex": ["hardcoded", "https://developers.openai.com/api/docs/models"],
  google: ["hardcoded", "https://ai.google.dev/gemini-api/docs/generate-content/thinking"],
  "kimi-coding": ["hardcoded", "https://platform.moonshot.ai/docs/guide/kimi-k3"],
  "kimi-moonshot": ["hardcoded", "https://platform.moonshot.ai/docs/guide/kimi-k3"],
  zai: ["hardcoded", "https://docs.z.ai/guides/llm/glm-5.3"],
  xai: ["hardcoded", "https://docs.x.ai/docs/models"],
  deepseek: ["hardcoded", "https://api-docs.deepseek.com/api/create-chat-completion"],
  hyper: ["API-derived (live /v1/models reasoning.effort_levels)", "https://docs.hyperbolic.xyz/docs/reasoning-effort"],
  clinepass: ["derived from slot maps", "https://docs.cline.bot/provider-config"],
  neuralwatt: ["hardcoded", "https://portal.neuralwatt.com/docs/api/chat-completions"],
  "opencode-go": ["hardcoded", "https://opencode.ai/docs/providers/"],
  commandcode: ["hardcoded (source-package tables)", "https://commandcode.ai/docs/provider"],
};

const CATALOGS = [
  ["anthropic", "anthropic", "anthropicModels"],
  ["openai", "openai", "openAIModels"],
  ["openai-codex", "openai", "openAICodexModels"],
  ["google", "google", "googleModels"],
  ["kimi-coding", "kimi", "kimiCodingModels"],
  ["kimi-moonshot", "kimi", "moonshotKimiModels"],
  ["zai", "zai", "zaiModels"],
  ["xai", "xai", "xaiModels"],
  ["deepseek", "deepseek", "deepseekModels"],
  ["hyper", "hyper", "hyperModels"],
  ["clinepass", "clinepass", "clinePassModels"],
  ["neuralwatt", "neuralwatt", "neuralWattModels"],
  ["opencode-go", "opencode-go", "openCodeGoModels"],
  ["commandcode", "commandcode", "commandCodeModels"],
];

const LIVE_SUITES = {
  anthropic: "packages/prism-providers/src/anthropic/__tests__/live.test.ts (output_config.effort probe)",
  google: "packages/prism-providers/src/google/__tests__/live.test.ts (thinkingLevel probe)",
  xai: "packages/prism-providers/src/xai/__tests__/live.test.ts (reasoning_effort probe)",
  "kimi-coding": "packages/prism-providers/src/kimi/__tests__/live.test.ts (K3 effort probe)",
  "kimi-moonshot": "packages/prism-providers/src/kimi/__tests__/live.test.ts (K3 effort probe)",
  zai: "packages/prism-providers/src/zai/__tests__/live.test.ts (GLM snap probe)",
};

const wireTest = (id) => `packages/prism-providers/src/__tests__/thinking-conformance.test.ts (walk: ${id})`;

const rows = [];
for (const [id, dir, exportName] of CATALOGS) {
  const models = await load(dir, exportName);
  const [source, url] = SOURCES[id];
  for (const model of models) {
    if (model.capabilities?.reasoning !== true) continue;
    rows.push({
      catalog: id,
      model: model.model,
      family: model.compat?.thinkingFamily ?? "(heuristic: reasoning_effort)",
      levels: model.capabilities?.thinkingLevels?.join(", ") ?? "—",
      source: model.capabilities?.thinkingLevels?.length ? `${source} — ${url}` : "toggle-only / heuristic passthrough",
      wire: wireTest(id),
      live: LIVE_SUITES[id] ?? "—",
    });
  }
}

const lines = [
  "# Thinking-coverage evidence matrix (2026-09-05)",
  "",
  "Generated by `scripts/generate-thinking-coverage.mjs` from the compiled provider catalogs —",
  "the exact data `packages/prism-providers/src/__tests__/thinking-conformance.test.ts` asserts.",
  "Regenerate after catalog changes: `node scripts/generate-thinking-coverage.mjs`.",
  "",
  "| Provider catalog | Model | Family stamp | Declared thinkingLevels | Levels source | Wire assertion | Live probe |",
  "| --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map(
    (r) => `| ${r.catalog} | \`${r.model}\` | ${r.family} | ${r.levels === "—" ? "—" : r.levels} | ${r.source} | ${r.wire} | ${r.live} |`,
  ),
  "",
  `Coverage: ${rows.length} reasoning-capable catalog models across ${CATALOGS.length} first-party catalogs.`,
  "Every model is machine-checked by the conformance walk; the live probes run only under `PRISM_LIVE_PROVIDER_TESTS=1` (plan 064 skip contract).",
  "",
];

writeFileSync(`${root}docs/_evidence/thinking-coverage-2026-09-05.md`, lines.join("\n"));
console.log(`wrote docs/_evidence/thinking-coverage-2026-09-05.md (${rows.length} rows)`);
