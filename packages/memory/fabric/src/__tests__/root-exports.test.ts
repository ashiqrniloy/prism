const BARREL_FILES = ["../exports.ts", "../scoped/index.ts"];

describe("memory-fabric root exports", () => {
  it("fabric_root_exports_only_the_stable_set", () => {
    expect(Object.keys(barrel).sort()).toEqual([...STABLE_VALUES].sort());
  });

  it("fabric_root_barrel_does_not_name_an_internal", () => {
    const source = BARREL_FILES.map((file) => readFileSync(fileURLToPath(new URL(file, import.meta.url)), "utf8"))
      .join("\n")
      .replace(/\/\*[\s\S]*?\*\//g, "")
      .replace(/\/\/.*$/gm, "");
    const present = INTERNAL_NAMES.filter((name) => new RegExp(`\\b${name}\\b`).test(source));
    expect(present).toEqual([]);
  });
});
